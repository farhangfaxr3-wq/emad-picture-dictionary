export function expandVocabulary(base: BaseWord[]): Word[] {
  const words: Word[] = [
    ...base.map((word) => ({
      ...word,
      group: seedGroups[word.id] || "Everyday words",
      partOfSpeech: "noun",
      art: word.id,
    })),
    ...entries.map(
      (
        [word, pronunciation, topic, group, definition, example, art],
        index,
      ): Word => ({
        id: word.replace(/ /g, "-"),
        word,
        pronunciation: `/${pronunciation}/`,
        topic,
        group,
        definition,
        example,
        art,
        level: index % 4 === 3 ? "Intermediate" : "Beginner",
        partOfSpeech: adjectives.has(word) ? "adjective" : "noun",
        related: [],
      }),
    ),
  ]
  return words.map((word) => ({
    ...word,
    related: [
      ...new Set([
        ...word.related,
        ...words
          .filter(
            (other) =>
              other.id !== word.id &&
              other.topic === word.topic &&
              other.group === word.group,
          )
          .map((other) => other.id),
        ...words
          .filter((other) => other.id !== word.id && other.topic === word.topic)
          .map((other) => other.id),
      ]),
    ].slice(0, 5),
  }))
}
